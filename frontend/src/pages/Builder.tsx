import { useEffect, useRef, useState } from "react";
import { ArrowLeft, Eye, Files, Monitor, Sparkles } from "lucide-react";
import { Link, useLocation } from "react-router-dom";
import BuildStepsPanel from "../components/BuildStepsPanel";
import CodeEditor from "../components/CodeEditor";
import FileExplorer from "../components/FileExplorer";
import Preview from "../components/Preview";
import Button from "../components/ui/button";
import { useBuilder } from "../hooks/useBuilder";
import { DEFAULT_AI_MODEL, type AIModelId } from "../constants/models";

export default function Builder() {
  const location = useLocation();
  const routeState = location.state as {
    prompt?: string;
    model?: AIModelId;
  } | null;
  const prompt = routeState?.prompt ?? "";
  const selectedModel = DEFAULT_AI_MODEL;
  const {
    files,
    fileCount,
    selectedFile,
    setSelectedFile,
    updateFileContent,
    buildSteps,
    isGenerating,
    generationError,
    handleGenerate,
  } = useBuilder(prompt);
  const [activeTab, setActiveTab] = useState<"preview" | "code">("preview");
  const [mobilePanel, setMobilePanel] = useState<"files" | "steps" | "none">(
    "none",
  );
  const hasAutoGenerated = useRef(false);

  useEffect(() => {
    if (!prompt.trim() || hasAutoGenerated.current) return;
    hasAutoGenerated.current = true;
    void handleGenerate(undefined, selectedModel);
  }, [handleGenerate, prompt, selectedModel]);

  const fileExplorer = (
    <FileExplorer
      files={files}
      onFileSelect={(file) => {
        setSelectedFile(file);
        setActiveTab("code");
        setMobilePanel("none");
      }}
      selectedFilePath={selectedFile?.path ?? null}
    />
  );

  return (
    <main className="flex h-screen flex-col overflow-hidden bg-[#080d18] text-white">
      <header className="flex shrink-0 items-center justify-between border-b border-white/10 bg-slate-950/80 px-4 py-3 md:px-6">
        <div className="flex min-w-0 items-center gap-3">
          <Link
            to="/"
            aria-label="Back to home"
            className="rounded-lg p-2 text-slate-400 transition hover:bg-white/5 hover:text-white"
          >
            <ArrowLeft size={18} />
          </Link>
          <div className="min-w-0">
            <div className="flex items-center gap-2 text-sm font-semibold">
              <Sparkles size={16} className="text-blue-400" />
              <span>Website Builder</span>
              <span className="hidden rounded-full border border-white/10 px-2 py-0.5 text-[10px] font-medium uppercase tracking-wide text-slate-400 sm:inline">
                Workspace
              </span>
            </div>
            <p className="mt-0.5 max-w-[50vw] truncate text-xs text-slate-400">
              {prompt || "Your generated website"}
            </p>
          </div>
        </div>
        <div className="hidden items-center gap-2 text-xs text-slate-400 sm:flex">
          <span className="h-2 w-2 rounded-full bg-emerald-400" />
          {fileCount} {fileCount === 1 ? "file" : "files"}
        </div>
      </header>

      <section className="grid min-h-0 flex-1 grid-cols-1 gap-3 overflow-hidden p-3 md:grid-cols-[minmax(250px,300px)_minmax(0,1fr)] md:p-4 xl:grid-cols-[minmax(260px,300px)_minmax(0,1fr)_minmax(300px,360px)]">
        <div className="hidden h-full min-h-0 md:block">
          <BuildStepsPanel
            steps={buildSteps}
            isGenerating={isGenerating}
            error={generationError}
            model={selectedModel}
            onGenerate={() => void handleGenerate(undefined, selectedModel)}
            onFollowup={(value, model) => handleGenerate(value, model)}
          />
        </div>

        <section className="flex min-h-0 min-w-0 flex-col overflow-hidden rounded-2xl border border-white/10 bg-slate-900/70 shadow-xl shadow-black/10">
          <div className="flex items-center justify-between border-b border-white/10 px-3 py-2">
            <div className="flex items-center gap-1">
              <Button
                variant="ghost"
                size="sm"
                aria-pressed={activeTab === "preview"}
                className={`gap-2 ${activeTab === "preview" ? "bg-white/10 text-white" : "text-slate-400"}`}
                onClick={() => setActiveTab("preview")}
              >
                <Eye size={15} /> Preview
              </Button>
              <Button
                variant="ghost"
                size="sm"
                aria-pressed={activeTab === "code"}
                className={`gap-2 ${activeTab === "code" ? "bg-white/10 text-white" : "text-slate-400"}`}
                onClick={() => setActiveTab("code")}
              >
                <Monitor size={15} /> Code
              </Button>
            </div>
            <span className="hidden text-xs text-slate-500 sm:block">
              Changes update the preview automatically
            </span>
          </div>
          <div className="min-h-0 flex-1 overflow-y-auto p-2 md:p-3">
            <div
              className={`h-full ${activeTab === "preview" ? "" : "hidden"}`}
            >
              <Preview files={files} />
            </div>
            <div
              className={`h-full overflow-hidden rounded-xl border border-white/10 bg-slate-950 ${activeTab === "code" ? "" : "hidden"}`}
            >
              <CodeEditor file={selectedFile} onChange={updateFileContent} />
            </div>
          </div>
        </section>

        <aside className="hidden min-h-0 overflow-y-auto rounded-2xl border border-white/10 bg-slate-900/80 p-4 xl:block">
          <div className="mb-4 flex items-center justify-between">
            <h2 className="flex items-center gap-2 text-sm font-semibold text-slate-100">
              <Files size={16} className="text-blue-400" /> Files
            </h2>
            <span className="text-xs text-slate-500">{fileCount} total</span>
          </div>
          {fileExplorer}
        </aside>

        <div className="fixed inset-x-3 bottom-3 z-10 flex gap-2 rounded-xl border border-white/10 bg-slate-950/95 p-2 shadow-xl backdrop-blur md:hidden">
          <Button
            variant={mobilePanel === "steps" ? "secondary" : "ghost"}
            size="sm"
            className="flex-1"
            onClick={() =>
              setMobilePanel(mobilePanel === "steps" ? "none" : "steps")
            }
          >
            Steps
          </Button>
          <Button
            variant={mobilePanel === "files" ? "secondary" : "ghost"}
            size="sm"
            className="flex-1"
            onClick={() =>
              setMobilePanel(mobilePanel === "files" ? "none" : "files")
            }
          >
            Files
          </Button>
        </div>
        {mobilePanel === "steps" && (
          <div className="fixed inset-x-3 bottom-16 top-20 z-20 flex flex-col rounded-2xl border border-white/10 bg-slate-950 p-2 shadow-2xl md:hidden">
            <div className="flex justify-end">
              <Button
                variant="ghost"
                size="sm"
                onClick={() => setMobilePanel("none")}
              >
                Close
              </Button>
            </div>
            <div className="min-h-0 flex-1">
              <BuildStepsPanel
                steps={buildSteps}
                isGenerating={isGenerating}
                error={generationError}
                model={selectedModel}
                onGenerate={() => void handleGenerate(undefined, selectedModel)}
                onFollowup={(value, model) => handleGenerate(value, model)}
              />
            </div>
          </div>
        )}
        {mobilePanel === "files" && (
          <div className="fixed inset-x-3 bottom-16 top-20 z-20 overflow-y-auto rounded-2xl border border-white/10 bg-slate-900 p-4 shadow-2xl md:hidden">
            <div className="mb-3 flex justify-end">
              <Button
                variant="ghost"
                size="sm"
                onClick={() => setMobilePanel("none")}
              >
                Close
              </Button>
            </div>
            {fileExplorer}
          </div>
        )}
      </section>
    </main>
  );
}
